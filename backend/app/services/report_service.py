    def _render_requirement_card(self, req: Dict[str, Any], styles: Dict[str, ParagraphStyle]) -> Table:
        req_id = req.get("requirement_id", "")
        title = req.get("title", "")
        priority = req.get("priority", "MEDIUM")
        ai_status = req.get("ai_status", "UNKNOWN")
        reasoning = req.get("reasoning", "")
        citations = req.get("evidence_citations", [])
        override = req.get("auditor_override")
        source_ref = req.get("source_reference", "")

        status_colors_map = {
            "SATISFIED": ("#059669", "#ecfdf5", "#a7f3d0"),
            "MISSING": ("#dc2626", "#fef2f2", "#fecaca"),
            "CONFLICT": ("#7c3aed", "#f5f3ff", "#ddd6fe"),
            "PARTIAL": ("#d97706", "#fffbeb", "#fde68a"),
        }
        status_color, status_bg, status_border = status_colors_map.get(
            ai_status, ("#475569", "#f8fafc", "#cbd5e1")
        )

        header_html = (
            f"<b>{req_id}</b>: {title} "
            f"<font color='#64748b' size='8'>[{priority}]</font>"
        )
        if source_ref:
            header_html += f" <font color='#94a3b8' size='7.5'>• Ref: {source_ref}</font>"

        status_pill = f"<font color='{status_color}'><b>{ai_status}</b></font>"

        citation_paragraphs = []
        if citations:
            for cit in citations:
                doc_name = cit.get("document_name", "Evidence Document")
                page = f"p. {cit.get('page_number')}" if cit.get("page_number") else ""
                sec = cit.get("section") or ""
                loc = " • ".join([x for x in [doc_name, page, sec] if x])
                quote = cit.get("quote", "").strip()

                citation_html = (
                    f"<b>Source:</b> <font color='#2563eb'>{loc}</font><br/>"
                    f"<i>&ldquo;{quote}&rdquo;</i>"
                )
                if cit.get("relevance"):
                    citation_html += f"<br/><font color='#475569' size='8'>Relevance: {cit.get('relevance')}</font>"

                citation_paragraphs.append(Paragraph(citation_html, styles["CitationBox"]))
        elif ai_status == "MISSING":
            citation_paragraphs.append(Paragraph(
                "<i>No verifiable evidence found in the uploaded submission artifacts.</i>",
                styles["NormalSmall"]
            ))

        override_html = ""
        if override:
            override_html = (
                f"<font color='#2563eb'><b>HUMAN AUDITOR OVERRIDE:</b></font> "
                f"Status adjusted from <b>{override.get('original_ai_status')}</b> to "
                f"<font color='#059669'><b>{override.get('overridden_status')}</b></font><br/>"
                f"<b>Reason:</b> {override.get('auditor_reason', '')}"
            )
            if override.get("auditor_note"):
                override_html += f"<br/><b>Note:</b> {override.get('auditor_note')}"

        card_content = [
            [
                Paragraph(header_html, styles["ReqTitle"]),
                Paragraph(status_pill, styles["ReqStatusBadge"]),
            ],
            [
                Paragraph(f"<b>AI Finding:</b> {reasoning}", styles["NormalSmall"]),
                "",
            ],
        ]

        for cp in citation_paragraphs:
            card_content.append([cp, ""])

        if override_html:
            card_content.append([Paragraph(override_html, styles["OverrideBox"]), ""])

        card_table = Table(card_content, colWidths=[6.2 * inch, 1.3 * inch])
        card_table.setStyle(TableStyle([
            ("SPAN", (0, 1), (1, 1)),
            ("SPAN", (0, 2), (1, 2)) if len(card_content) > 2 else ("NOP", (0, 0), (0, 0)),
            ("SPAN", (0, 3), (1, 3)) if len(card_content) > 3 else ("NOP", (0, 0), (0, 0)),
            ("SPAN", (0, 4), (1, 4)) if len(card_content) > 4 else ("NOP", (0, 0), (0, 0)),
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#ffffff")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ("LINEBELOW", (0, 0), (-1, 0), 0.5, colors.HexColor(status_border)),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ]))
        return card_table

    def _render_conflict_card(self, conf: Dict[str, Any], styles: Dict[str, ParagraphStyle]) -> Table:
        fact_label = conf.get("fact_label") or conf.get("fact", "Factual Contradiction")
        req_id = conf.get("related_requirement_id", "")
        src_a = conf.get("source_a", {})
        src_b = conf.get("source_b", {})
        explanation = conf.get("explanation", "")
        rec_action = conf.get("recommended_action", "")

        cit_a = src_a.get("citation", {}) if isinstance(src_a, dict) else {}
        cit_b = src_b.get("citation", {}) if isinstance(src_b, dict) else {}
        val_a = src_a.get("value", "") if isinstance(src_a, dict) else ""
        val_b = src_b.get("value", "") if isinstance(src_b, dict) else ""
        doc_a = sanitize_filename(cit_a.get("document_name", "Source A"))
        doc_b = sanitize_filename(cit_b.get("document_name", "Source B"))

        comp_html_a = (
            f"<b>Source A:</b> <font color='#2563eb'>{doc_a}</font><br/>"
            f"<b>Extracted Value:</b> <font color='#dc2626'><b>{val_a}</b></font><br/>"
            f"<i>&ldquo;{cit_a.get('quote', '')}&rdquo;</i>"
        )
        comp_html_b = (
            f"<b>Source B:</b> <font color='#2563eb'>{doc_b}</font><br/>"
            f"<b>Extracted Value:</b> <font color='#dc2626'><b>{val_b}</b></font><br/>"
            f"<i>&ldquo;{cit_b.get('quote', '')}&rdquo;</i>"
        )

        card_data = [
            [
                Paragraph(f"<b>Conflict on {fact_label}</b> ({req_id})", styles["ReqTitle"]),
                Paragraph("<font color='#7c3aed'><b>CONFLICT</b></font>", styles["ReqStatusBadge"]),
            ],
            [
                Paragraph(comp_html_a, styles["CitationBox"]),
                Paragraph(comp_html_b, styles["CitationBox"]),
            ],
            [
                Paragraph(f"<b>Discrepancy:</b> {explanation}<br/><b>Resolution Action:</b> {rec_action}", styles["NormalSmall"]),
                "",
            ],
        ]

        table = Table(card_data, colWidths=[3.75 * inch, 3.75 * inch])
        table.setStyle(TableStyle([
            ("SPAN", (0, 0), (0, 0)),
            ("SPAN", (0, 2), (1, 2)),
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#faf5ff")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#ddd6fe")),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ]))
        return table

