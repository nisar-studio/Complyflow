    @staticmethod
    def _format_date(iso_str: Optional[str]) -> str:
        if not iso_str:
            return "—"
        try:
            dt = datetime.fromisoformat(iso_str.replace("Z", "+00:00"))
            return dt.strftime("%Y-%m-%d %H:%M UTC")
        except Exception:
            return str(iso_str)


